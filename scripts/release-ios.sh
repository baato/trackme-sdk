#!/usr/bin/env bash
# Builds the iOS release and writes a SwiftPM Package.swift at the repo root, so apps can add the SDK by git URL.
#
#   scripts/release-ios.sh 0.2.0 https://github.com/<owner>/<repo>/releases/download/0.2.0
#
# Then: upload build/release-ios/0.2.0/TrackMeSDK.xcframework.zip to that release URL,
# commit Package.swift, tag the commit "0.2.0" and push the tag. See docs/05-releasing.md.
set -euo pipefail

VERSION="${1:?usage: scripts/release-ios.sh <version> <download-base-url>}"
BASE_URL="${2:?usage: scripts/release-ios.sh <version> <download-base-url>}"
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT"

echo "▶ Building TrackMeSDK.xcframework (release) for $VERSION"
./gradlew :trackme-sdk:assembleTrackMeSDKReleaseXCFramework -Ptrackme.version="$VERSION"

OUT="$ROOT/build/release-ios/$VERSION"
mkdir -p "$OUT"
ZIP="$OUT/TrackMeSDK.xcframework.zip"
rm -f "$ZIP"
(cd trackme-sdk/build/XCFrameworks/release && zip -qry "$ZIP" TrackMeSDK.xcframework)

CHECKSUM="$(swift package compute-checksum "$ZIP")"
echo "▶ Checksum $CHECKSUM"

cat > "$ROOT/Package.swift" <<EOF
// swift-tools-version: 5.9
// GENERATED by scripts/release-ios.sh for $VERSION. Do not edit by hand.
import PackageDescription

let package = Package(
    name: "TrackMe",
    platforms: [.iOS(.v15)],
    products: [
        .library(name: "TrackMeSDK", targets: ["TrackMeSDK"]),
        .library(name: "TrackMeLiveActivity", targets: ["TrackMeLiveActivity"]),
    ],
    targets: [
        .binaryTarget(
            name: "TrackMeSDK",
            url: "$BASE_URL/TrackMeSDK.xcframework.zip",
            checksum: "$CHECKSUM"
        ),
        .target(name: "TrackMeLiveActivity", path: "TrackMeLiveActivity/Sources/TrackMeLiveActivity"),
    ]
)
EOF

echo "✔ Wrote Package.swift and $ZIP"
echo "  Next: upload the zip to $BASE_URL/, commit Package.swift, tag $VERSION, push the tag."
